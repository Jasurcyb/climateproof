// Builds js/data.js from NOAA GML Mauna Loa monthly CO2 (public domain).
// Usage: node tools/build-data.js
const fs = require("fs");
const path = require("path");

const raw = fs.readFileSync(path.join(__dirname, "co2_mm_mlo.txt"), "utf8");
const rows = [];
for (const line of raw.split("\n")) {
  if (line.startsWith("#")) continue;
  const p = line.trim().split(/\s+/);
  if (p.length < 6) continue;
  const [yy, mm, dec, avg, deseas, ndays, sdev, unc] = p.map(Number);
  if (!Number.isFinite(avg) || avg <= 0 || avg === -9.99) continue; // -9.99 marks missing months
  rows.push([yy, mm, dec, +avg.toFixed(2)]);
}
const out = `// Generated by tools/build-data.js — do not edit.
// Source: NOAA Global Monitoring Laboratory — Mauna Loa monthly mean CO2 (Scripps/NOAA Keeling curve).
// Public domain data. https://gml.noaa.gov/ccgg/trends/
(typeof window !== "undefined" ? window : globalThis).CLIMATEPROOF_META = {
  n: ${rows.length},
  first: ${rows[0][2]},
  last: ${rows[rows.length - 1][2]},
  firstPpm: ${rows[0][3]},
  lastPpm: ${rows[rows.length - 1][3]},
  source: "NOAA Global Monitoring Laboratory, Mauna Loa Observatory",
  url: "https://gml.noaa.gov/ccgg/trends/"
};
(typeof window !== "undefined" ? window : globalThis).CLIMATEPROOF_CO2 = ${JSON.stringify(rows)};
`;
fs.mkdirSync(path.join(__dirname, "..", "js"), { recursive: true });
fs.writeFileSync(path.join(__dirname, "..", "js", "data.js"), out);
console.log(`Wrote js/data.js with ${rows.length} monthly means (${rows[0][0]}-${rows[0][1]} .. ${rows[rows.length - 1][0]}-${rows[rows.length - 1][1]}, ${rows[0][3]} -> ${rows[rows.length - 1][3]} ppm)`);
